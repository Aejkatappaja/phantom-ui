/**
 * Emits dist/phantom-ui.standalone.d.ts: a declaration file with no external references,
 * so the standalone bundle can be vendored into a project that cannot install anything.
 *
 * Derived from the real emitted declarations rather than hand written, so it cannot drift
 * away from the class it describes. Three substitutions make it self-contained:
 *
 * - `extends LitElement` becomes `extends HTMLElement`. Narrower, not wrong: LitElement
 *   extends HTMLElement. `updateComplete` is redeclared by hand because it is the one
 *   Lit member consumers actually await.
 * - `static styles: CSSResult` is dropped. It is an implementation detail and the only
 *   reason `lit` was imported for a type.
 * - `render()` is dropped. It returns a lit-html template and is never called by a
 *   consumer.
 */
import { readFile, writeFile } from "node:fs/promises";

const DIST = "dist";

/** Drops both `import x from "./y"` and the bare side-effect form `import "./y"`. */
const stripLocalImports = (dts) =>
	dts
		.split("\n")
		.filter(
			(line) =>
				!/^(import|export)\s.*from\s+"\.\/[^"]+"/.test(line) &&
				!/^import\s+"\.\/[^"]+";/.test(line),
		)
		.join("\n");

const main = readFile(`${DIST}/phantom-ui.d.ts`, "utf8");
const types = readFile(`${DIST}/types.d.ts`, "utf8");

const [mainDts, typesDts] = await Promise.all([main, types]);

const body = stripLocalImports(mainDts)
	.replace(/^import type \{ CSSResult \} from "lit";\n/m, "")
	.replace(/^import \{ LitElement \} from "lit";\n/m, "")
	.replace(
		"export declare class PhantomUi extends LitElement {",
		"export declare class PhantomUi extends HTMLElement {",
	)
	.replace(/^\s*static styles: CSSResult;\n/m, "")
	.replace(/^\s*render\(\): import\("lit-html"\)\.TemplateResult<1>;\n/m, "")
	.replace(
		"export declare class PhantomUi extends HTMLElement {",
		"export declare class PhantomUi extends HTMLElement {\n    /** Resolves once the element has finished its pending render. */\n    readonly updateComplete: Promise<boolean>;",
	);

const out = `// Generated by scripts/generate-standalone-types.mjs. Do not edit.
//
// Declarations for the standalone bundle, with no imports, so both files can be copied
// into a project that has no package manager access. The class is declared as an
// HTMLElement subclass: at runtime it is a LitElement, which is an HTMLElement, so this
// is a narrower view of the same object rather than a different one.

${stripLocalImports(typesDts).trim()}

${body.trim()}
`;

await writeFile(`${DIST}/phantom-ui.standalone.d.ts`, out);

const leftovers = [
	...out.matchAll(/from\s+"([^"]+)"|import\("([^"]+)"\)|^import\s+"([^"]+)";/gm),
].map((m) => m[1] ?? m[2] ?? m[3]);
if (leftovers.length > 0) {
	console.error(`standalone types still reference: ${[...new Set(leftovers)].join(", ")}`);
	process.exit(1);
}
console.log("wrote dist/phantom-ui.standalone.d.ts (no external references)");
